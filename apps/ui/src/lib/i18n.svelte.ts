const messages: Record<ResolvedLocale, Messages> = {
  en,
  'zh-CN': zhCN,
};

function detectSystemLocale(): ResolvedLocale {
  if (typeof navigator === 'undefined') return 'en';
  const values = [navigator.language, ...(navigator.languages ?? [])].filter(Boolean);
  return values.some((locale) => locale.toLowerCase().startsWith('zh')) ? 'zh-CN' : 'en';
}

function coerceLocale(value: unknown): LocaleSetting {
  return value === 'en' || value === 'zh-CN' || value === 'system' ? value : 'system';
}

class I18nStore {
  locale = $state<LocaleSetting>('system');
  systemLocale = $state<ResolvedLocale>(detectSystemLocale());

  get resolvedLocale(): ResolvedLocale {
    return this.locale === 'system' ? this.systemLocale : this.locale;
  }

  setLocale(locale: LocaleSetting): void {
    this.locale = locale;
    this.systemLocale = detectSystemLocale();
    if (typeof document !== 'undefined') {
      document.documentElement.lang = this.resolvedLocale;
    }
  }

  async load(rpc: RpcClient): Promise<void> {
    try {
      const r = await rpc.call<{ value: unknown }>('settings.get', { key: 'application' });
      const value = r.value && typeof r.value === 'object'
        ? (r.value as Record<string, unknown>).locale
        : undefined;
      this.setLocale(coerceLocale(value));
    } catch {
      this.setLocale('system');
    }
  }

  t(key: string, vars: Record<string, string | number | boolean | null | undefined> = {}): string {
    const template = messages[this.resolvedLocale][key] ?? messages.en[key] ?? key;
    return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_match, name: string) => {
      const value = vars[name];
      return value == null ? '' : String(value);
    });
  }
}

